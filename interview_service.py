def _row_to_dict(cursor, row):
    columns = [d[0].lower() for d in cursor.description]
    return dict(zip(columns, row))


def get_all_feedback():
    conn = get_connection()
    try:
        cur = conn.cursor()
        cur.execute("SELECT * FROM SYS.INTERVIEW_FEEDBACK ORDER BY interview_date ASC, id ASC")
        return [_row_to_dict(cur, r) for r in cur.fetchall()]
    finally:
        conn.close()


def get_candidate_feedback(candidate_name: str):
    conn = get_connection()
    try:
        cur = conn.cursor()
        cur.execute(
            "SELECT * FROM SYS.INTERVIEW_FEEDBACK WHERE candidate_name = :1 ORDER BY interview_date ASC, id ASC",
            [candidate_name],
        )
        return [_row_to_dict(cur, r) for r in cur.fetchall()]
    finally:
        conn.close()


def get_feedback_by_id(feedback_id: int):
    conn = get_connection()
    try:
        cur = conn.cursor()
        cur.execute("SELECT * FROM SYS.INTERVIEW_FEEDBACK WHERE id = :1", [feedback_id])
        row = cur.fetchone()
        return _row_to_dict(cur, row) if row else None
    finally:
        conn.close()


