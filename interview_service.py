ALL_SCORE_FIELDS = ROUND1_FIELDS + ROUND2_FIELDS

REC_TO_SCORE = {"Strong Hire": 4, "Hire": 3, "No Hire": 2, "Strong No Hire": 1}
SCORE_TO_REC = {v: k for k, v in REC_TO_SCORE.items()}
POSITIVE_RECS = {"Hire", "Strong Hire"}
NEGATIVE_RECS = {"No Hire", "Strong No Hire"}


def _final_recommendation(recs):
    has_positive = any(r in POSITIVE_RECS for r in recs)
    has_negative = any(r in NEGATIVE_RECS for r in recs)
    if has_positive and has_negative:
        return "Split Decision - Needs Discussion"
    avg = statistics.mean(REC_TO_SCORE[r] for r in recs)
    rounded = min(max(round(avg), 1), 4)
    return SCORE_TO_REC[rounded]


def _scored_fields(row):
    """Which scorecard (round1 or round2) this row was actually filled in with.
    The submit form only enables/POSTs one set at a time, so a row will have
    real values for exactly one set and NULLs for the other."""
    if any(row.get(f) is not None for f in ROUND1_FIELDS):
        return ROUND1_FIELDS, ROUND1_LABELS
    return ROUND2_FIELDS, ROUND2_LABELS


def consolidate(rows):
    by_candidate = defaultdict(list)
    for row in rows:
        by_candidate[row["candidate_name"]].append(row)

    results = []
    for candidate, entries in by_candidate.items():
        position = entries[-1]["position"]

        dim_values = defaultdict(list)   # label -> [scores...] across whichever entries used that dimension
        entry_avgs = []                  # one overall average per entry (round), for the candidate's overall score

        for e in entries:
            fields, labels = _scored_fields(e)
            vals = [e[f] for f in fields if e.get(f) is not None]
            if not vals:
                continue
            entry_avgs.append(statistics.mean(vals))
            for f in fields:
                if e.get(f) is not None:
                    dim_values[labels[f]].append(e[f])

        dim_avgs = {label: round(statistics.mean(vals), 2) for label, vals in dim_values.items()}
        overall_avg = round(statistics.mean(entry_avgs), 2) if entry_avgs else 0.0
        recs = [e["recommendation"] for e in entries]
        final_rec = _final_recommendation(recs)

        results.append({
            "candidate": candidate,
            "position": position,
            "rounds_completed": len(entries),
            "dimension_averages": dim_avgs,
            "overall_average": overall_avg,
            "final_recommendation": final_rec,
        })

    results.sort(key=lambda r: r["overall_average"], reverse=True)
    return results


