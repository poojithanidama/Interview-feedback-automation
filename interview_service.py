@asynccontextmanager
async def lifespan(app: FastAPI):
    init_db(seed_if_empty=False)
    yield


app = FastAPI(title="Interview Feedback Microservice", lifespan=lifespan)
app.add_middleware(
    CORSMiddleware,
    allow_origins=["*"],  # tighten this to the Flask front end's origin in production
    allow_methods=["*"],
    allow_headers=["*"],
)


class FeedbackIn(BaseModel):
    candidate_name: str
    position: str
    interview_round: str
    interviewer_name: str
    interview_date: str

    round1_communication_soft_skills: Optional[int] = None
    round1_basic_technical_skill_assessment: Optional[int] = None
    round1_project_explanation: Optional[int] = None
    round1_logical_ability: Optional[int] = None
    round1_resume: Optional[int] = None

    round2_introduction: Optional[int] = None
    round2_general_programming: Optional[int] = None
    round2_python_basics: Optional[int] = None
    round2_python_advanced: Optional[int] = None
    round2_oops: Optional[int] = None
    round2_projects: Optional[int] = None
    round2_pending_resume: Optional[int] = None
    round2_other_technologies: Optional[int] = None
    round2_good_attitude: Optional[int] = None
    round2_confidence: Optional[int] = None

    recommendation: str
    comments: str = ""


@app.get("/health")
def health():
    return {"service": "interview_service", "status": "healthy"}


@app.get("/api/interview/feedback")
def api_all_feedback():
    """Every raw row + the per-candidate consolidated view (dashboard needs both)."""
    rows = get_all_feedback()
    return {
        "rows": rows,
        "candidates": consolidate(rows) if rows else [],
        "total_submissions": len(rows),
    }


@app.get("/api/interview/candidate/{candidate_name}")
def api_candidate_detail(candidate_name: str):
    rows = get_candidate_feedback(candidate_name)
    if not rows:
        raise HTTPException(status_code=404, detail="Candidate not found")
    summary = consolidate(rows)[0]
    return {"candidate": summary, "rounds": rows}


@app.post("/api/interview/feedback", status_code=201)
def api_submit_feedback(payload: FeedbackIn):
    data = payload.model_dump()
    data["candidate_name"] = data["candidate_name"].strip()
    data["comments"] = data["comments"].strip()
    insert_feedback(data)
    return {"candidate_name": data["candidate_name"]}


@app.get("/api/interview/feedback/{feedback_id}")
def api_get_feedback(feedback_id: int):
    entry = get_feedback_by_id(feedback_id)
    if not entry:
        raise HTTPException(status_code=404, detail="Feedback entry not found")
    return entry


@app.put("/api/interview/feedback/{feedback_id}")
def api_update_feedback(feedback_id: int, payload: FeedbackIn):
    if not get_feedback_by_id(feedback_id):
        raise HTTPException(status_code=404, detail="Feedback entry not found")
    data = payload.model_dump()
    data["candidate_name"] = data["candidate_name"].strip()
    data["comments"] = data["comments"].strip()
    update_feedback(feedback_id, data)
    return {"candidate_name": data["candidate_name"]}


@app.delete("/api/interview/feedback/{feedback_id}")
def api_delete_feedback(feedback_id: int):
    entry = get_feedback_by_id(feedback_id)
    if not entry:
        raise HTTPException(status_code=404, detail="Feedback entry not found")
    delete_feedback_entry(feedback_id)
    remaining = get_candidate_feedback(entry["candidate_name"])
    return {"candidate_name": entry["candidate_name"], "candidate_has_remaining_rounds": bool(remaining)}


@app.delete("/api/interview/candidate/{candidate_name}")
def api_delete_candidate(candidate_name: str):
    delete_candidate(candidate_name)
    return {"status": "deleted", "candidate_name": candidate_name}


